/* =============================================================================
 * SimEarth 2.0 — pack the built art into the atlas and write it out
 * -----------------------------------------------------------------------------
 * Shared by the CLI (tools/terrain-atlas.js) and tests/terrain.test.js, which
 * rebuilds the atlas in memory to prove the committed one matches the recipes.
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const C = require('./catalog');
const P = require('./palette');
const { Tex } = require('./kit');

const ROOT = path.join(__dirname, '..', '..');
const ATLAS_WIDTH = 1024;

/* ---------------------------------------------------------------- packing -- */

/** Shelf packing, tallest first; returns the atlas size and sets item.x/y. */
function pack(items) {
  const order = [...items].sort((a, b) => b.tex.h - a.tex.h || b.tex.w - a.tex.w || (a.key < b.key ? -1 : 1));
  let x = 0;
  let y = 0;
  let shelf = 0;
  for (const it of order) {
    if (x + it.tex.w > ATLAS_WIDTH) { x = 0; y += shelf; shelf = 0; }
    it.x = x;
    it.y = y;
    x += it.tex.w;
    shelf = Math.max(shelf, it.tex.h);
  }
  return { w: ATLAS_WIDTH, h: Math.ceil((y + shelf) / 8) * 8 };
}

function rect(it) {
  return { x: it.x, y: it.y, w: it.tex.w, h: it.tex.h };
}

/** Pack a full build (every family) into atlas pixels and the manifest. */
function assemble(art) {
  const items = [];
  const add = (key, tex) => { const it = { key, tex }; items.push(it); return it; };
  const maskIndex = P.c('mask0');

  const mats = {};
  for (const m of C.MATERIALS) mats[m.id] = art.materials[m.id].map((t, d) => add(`m:${m.id}:${d}`, t));
  const ovs = {};
  for (const o of C.OVERLAYS) ovs[o.id] = add(`o:${o.id}`, art.overlays[o.id]);
  const masks = art.masks.map((vars, kase) => vars.map((mask, v) => {
    const t = new Tex(16, 16);
    mask.forEach((on, i) => { t.px[i] = on ? maskIndex : 0; });
    return add(`k:${kase}:${v}`, t);
  }));
  const objs = {};
  for (const o of C.OBJECTS) objs[o.id] = art.objects[o.id].map((v, n) => ({ v, it: add(`b:${o.id}:${n}`, v.tex) }));

  const size = pack(items);
  const px = new Uint8Array(size.w * size.h);
  for (const it of items) {
    for (let y = 0; y < it.tex.h; y++) {
      for (let x = 0; x < it.tex.w; x++) px[(it.y + y) * size.w + it.x + x] = it.tex.px[y * it.tex.w + x];
    }
  }

  const manifest = {
    version: 1,
    tile: 16,
    width: size.w,
    height: size.h,
    palette: P.PALETTE,
    ramps: P.RAMP_INDICES,
    maskIndex,
    materials: Object.fromEntries(C.MATERIALS.map((m, i) => [m.id, {
      name: m.name, family: m.family, rank: i + 1, size: m.size, densities: mats[m.id].map(rect),
    }])),
    overlays: Object.fromEntries(C.OVERLAYS.map((o) => [o.id, { name: o.name, family: o.family, size: o.size, rect: rect(ovs[o.id]) }])),
    masks: masks.map((vars) => vars.map(rect)),
    objects: Object.fromEntries(C.OBJECTS.map((o) => [o.id, {
      name: o.name, group: o.group, kind: o.kind, family: o.family,
      variants: objs[o.id].map(({ v, it }) => ({
        rect: rect(it), ax: Math.floor(it.tex.w / 2), ay: it.tex.h - 1, size: v.size || '', form: v.form ?? v.index,
      })),
    }])),
    landscapeIds: C.LANDSCAPES.map((l) => l.id),
    landscapes: Object.fromEntries(C.LANDSCAPES.map((l) => [l.id, {
      name: l.name, materials: l.materials, objects: l.objects || {}, abiotic: l.abiotic || 0,
    }])),
    groups: C.GROUPS,
    abiotic: C.ABIOTIC,
  };
  return { px, size, manifest };
}

/* ---------------------------------------------------------------- output -- */

const TS_HEADER = `/* =============================================================================
 * SimEarth 2.0 — terrain atlas (GENERATED by tools/terrain-atlas.js — do not edit)
 * -----------------------------------------------------------------------------
 * The landscape pixel art as one indexed PNG (data URI: no fetch, no tainted
 * canvas over file://) and the manifest that says where everything is in it.
 * Contract and ids: tools/terrain/catalog.js · spec: docs/biomes-spec.md.
 * ========================================================================== */

namespace SE {
  export interface TerrainRect { readonly x: number; readonly y: number; readonly w: number; readonly h: number }
  export interface TerrainMaterial {
    readonly name: string; readonly family: string; readonly rank: number; readonly size: number;
    readonly densities: readonly TerrainRect[];
  }
  export interface TerrainOverlay { readonly name: string; readonly family: string; readonly size: number; readonly rect: TerrainRect }
  /** One drawing of an object; (ax, ay) is its foot inside rect. */
  export interface TerrainSprite { readonly rect: TerrainRect; readonly ax: number; readonly ay: number; readonly size: string; readonly form: number }
  export interface TerrainObject {
    readonly name: string; readonly group: string | null; readonly kind: string; readonly family: string;
    readonly variants: readonly TerrainSprite[];
  }
  export interface TerrainSubstrates { readonly rock: string; readonly sand: string; readonly soil: string; readonly mire: string }
  export interface TerrainLandscape {
    readonly name: string; readonly materials: TerrainSubstrates;
    /** Expected objects per tile by kind, indexed by density step. */
    readonly objects: { readonly tree?: readonly number[]; readonly bush?: readonly number[]; readonly low?: readonly number[] };
    readonly abiotic: number;
  }
  export interface TerrainGroupObject { readonly id: string; readonly where: '*' | readonly string[] }
  export interface TerrainGroup {
    readonly name: string; readonly objects: readonly TerrainGroupObject[];
    readonly swatch: { readonly material: string; readonly density: number } | null;
  }
  export interface TerrainManifest {
    readonly version: number; readonly tile: number; readonly width: number; readonly height: number;
    /** [r, g, b, a] per palette index; 0 is transparent. */
    readonly palette: readonly (readonly number[])[];
    /** Ramp name → palette indices, dark to light. */
    readonly ramps: Readonly<Record<string, readonly number[]>>;
    /** Palette index that marks "inside" in an edge mask. */
    readonly maskIndex: number;
    readonly materials: Readonly<Record<string, TerrainMaterial>>;
    readonly overlays: Readonly<Record<string, TerrainOverlay>>;
    /** [case: corner bits TL=1 TR=2 BL=4 BR=8][variant]. */
    readonly masks: readonly (readonly TerrainRect[])[];
    readonly objects: Readonly<Record<string, TerrainObject>>;
    /** Landscape ids in the order of the simulation's Landscape enum. */
    readonly landscapeIds: readonly string[];
    readonly landscapes: Readonly<Record<string, TerrainLandscape>>;
    /** Flora id → the objects (or ground swatch) that show the group. */
    readonly groups: Readonly<Record<string, TerrainGroup>>;
    readonly abiotic: readonly { readonly id: string; readonly where: readonly string[] }[];
  }
`;

/** The generated TypeScript source for the atlas and its manifest. */
function renderTs(png, manifest) {
  return `${TS_HEADER}
  export const TERRAIN_MANIFEST: TerrainManifest = ${JSON.stringify(manifest)};

  export const TERRAIN_ATLAS_PNG = 'data:image/png;base64,${png.toString('base64')}';
}
`;
}

function writeOutputs(png, manifest) {
  const dir = path.join(ROOT, 'assets', 'terrain');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'atlas.png'), png);
  fs.writeFileSync(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 1)}\n`);
  fs.writeFileSync(path.join(ROOT, 'src', 'terrainatlas.ts'), renderTs(png, manifest));
  console.log(`wrote assets/terrain/atlas.png (${manifest.width}×${manifest.height}, ${(png.length / 1024).toFixed(1)} KB), manifest.json, src/terrainatlas.ts`);
}

module.exports = { assemble, renderTs, writeOutputs };
