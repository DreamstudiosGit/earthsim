/* =============================================================================
 * SimEarth 2.0 — pack the effect frames into the fx atlas and write it out
 * -----------------------------------------------------------------------------
 * Shared by the CLI (tools/fx-atlas.js) and tests/fxatlas.test.js, which
 * rebuilds the atlas in memory to prove the committed one matches the
 * recipes. Every frame of a sprite or texture sits in one row of the atlas.
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const C = require('./catalog');
const P = require('../terrain/palette');

const ROOT = path.join(__dirname, '..', '..');
const ATLAS_WIDTH = 256;

/** Shelf packing of frame strips, tallest first; sets item.x/y, returns the atlas size. */
function pack(items) {
  // A strip never wraps: the atlas is as wide as the widest one (ash and dust clouds run past 256 px).
  const width = Math.max(ATLAS_WIDTH, ...items.map((it) => Math.ceil(it.w / 8) * 8));
  const order = [...items].sort((a, b) => b.h - a.h || b.w - a.w || (a.key < b.key ? -1 : 1));
  let x = 0;
  let y = 0;
  let shelf = 0;
  for (const it of order) {
    if (x + it.w > width) { x = 0; y += shelf; shelf = 0; }
    it.x = x;
    it.y = y;
    x += it.w;
    shelf = Math.max(shelf, it.h);
  }
  return { w: width, h: Math.ceil((y + shelf) / 8) * 8 };
}

function assemble(art) {
  const items = [];
  const strip = (key, frames) => {
    const fw = frames[0].w;
    const it = { key, frames, w: fw * frames.length, h: frames[0].h };
    items.push(it);
    return it;
  };
  const spriteItems = C.SPRITES.filter((s) => art.sprites[s.id]).map((s) => [s, strip(`s:${s.id}`, art.sprites[s.id])]);
  const textureItems = C.TEXTURES.filter((t) => art.textures[t.id]).map((t) => [t, strip(`t:${t.id}`, art.textures[t.id])]);
  const size = pack(items);
  const px = new Uint8Array(size.w * size.h);
  for (const it of items) {
    it.frames.forEach((t, f) => {
      for (let y = 0; y < t.h; y++) {
        for (let x = 0; x < t.w; x++) px[(it.y + y) * size.w + it.x + f * t.w + x] = t.px[y * t.w + x];
      }
    });
  }
  const rects = (it) => it.frames.map((t, f) => ({ x: it.x + f * t.w, y: it.y, w: t.w, h: t.h }));
  const manifest = {
    version: 1,
    width: size.w,
    height: size.h,
    sprites: Object.fromEntries(spriteItems.map(([s, it]) => [s.id, {
      name: s.name, w: s.w, h: s.h, fps: s.fps, loop: s.loop ?? s.frames, layer: s.layer,
      ax: s.anchor === 'foot' ? Math.floor(s.w / 2) : s.w / 2,
      ay: s.anchor === 'foot' ? s.h - 1 : s.h / 2,
      anchor: s.anchor, mouth: s.mouth ?? null, frames: rects(it),
    }])),
    textures: Object.fromEntries(textureItems.map(([t, it]) => [t.id, {
      name: t.name, size: t.size, fps: t.fps, rim: t.rim ? P.PALETTE[P.c(t.rim)].slice(0, 3) : null, frames: rects(it),
    }])),
  };
  return { px, size, manifest };
}

const TS_HEADER = `/* =============================================================================
 * SimEarth 2.0 — effect atlas (GENERATED by tools/fx-atlas.js — do not edit)
 * -----------------------------------------------------------------------------
 * The disaster effects as one indexed PNG in the terrain palette (data URI:
 * no fetch, no tainted canvas over file://) and the manifest that says where
 * each frame is and how it stands on the map.
 * Contract and ids: tools/fx/catalog.js · spec: docs/ereignisse-spec.md §2.4.
 * ========================================================================== */

namespace SE {
  export interface FxRect { readonly x: number; readonly y: number; readonly w: number; readonly h: number }
  export interface FxSprite {
    readonly name: string; readonly w: number; readonly h: number;
    /** Frames per second; 0 for a still sprite whose frames are variants. */
    readonly fps: number;
    /** Frames that repeat; the rest play once after them. */
    readonly loop: number;
    readonly layer: 'object' | 'top';
    /** The point (inside the frame) that sits on the anchor: the foot or the centre. */
    readonly ax: number; readonly ay: number;
    readonly anchor: 'foot' | 'center';
    /** A vent's crater, inside the frame, where the eruption column stands. */
    readonly mouth: readonly number[] | null;
    readonly frames: readonly FxRect[];
  }
  export interface FxTexture {
    readonly name: string; readonly size: number; readonly fps: number;
    /** The darker edge drawn where the layer meets plain ground; null for a film. */
    readonly rim: readonly number[] | null;
    readonly frames: readonly FxRect[];
  }
  export interface FxManifest {
    readonly version: number; readonly width: number; readonly height: number;
    readonly sprites: Readonly<Record<string, FxSprite>>;
    readonly textures: Readonly<Record<string, FxTexture>>;
  }
`;

function renderTs(png, manifest) {
  return `${TS_HEADER}
  export const FX_MANIFEST: FxManifest = ${JSON.stringify(manifest)};

  export const FX_ATLAS_PNG = 'data:image/png;base64,${png.toString('base64')}';
}
`;
}

/** Into the repository, or with `dir` both files into that folder (an agent's own build). */
function writeOutputs(png, manifest, dir = null) {
  const pngDir = dir ?? path.join(ROOT, 'assets', 'fx');
  const tsFile = dir ? path.join(dir, 'fxatlas.ts') : path.join(ROOT, 'src', 'fxatlas.ts');
  fs.mkdirSync(pngDir, { recursive: true });
  fs.writeFileSync(path.join(pngDir, 'atlas.png'), png);
  fs.writeFileSync(tsFile, renderTs(png, manifest));
  console.log(`wrote ${path.join(pngDir, 'atlas.png')} (${manifest.width}×${manifest.height}, ${(png.length / 1024).toFixed(1)} KB), ${tsFile}`);
}

module.exports = { assemble, renderTs, writeOutputs };
